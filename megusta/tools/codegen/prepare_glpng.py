#!/usr/bin/env python3
"""Reproduce pinned glpng with mipmap/gamma changes and the authored reader patch."""
from pathlib import Path
import difflib, hashlib, json, shutil, subprocess, tempfile

root = Path(__file__).resolve().parents[2]
source = root/'upstream/libglpng-1.45'
vendor = root/'vendor/glpng'
path = Path('src/glpng.c')
original = (source/path).read_bytes()
bridge = b'''
/* MG-GLPNG-001: expose the existing internal algorithm to the original SSG
 * image upload adapter (004b63f0 -> 004dd0b0). No algorithm change. */
void megusta_glpng_buildMipmaps(GLint components, GLint width, GLint height,
                              GLenum format, const unsigned char *data, int filter)
{
    Build2DMipmaps(components, width, height, format, data, filter);
}
'''
gamma = b"""
/* MG-GLPNG-002: game00461990 shares a byte lookup with the TXF loader. */
#include <math.h>
static unsigned char megusta_gamma_table[256];
static int megusta_gamma_active;
static void megusta_glpng_updateGamma(double gamma) {
    int i; megusta_gamma_active=0;
    for(i=0;i<256;i++) megusta_gamma_table[i]=(unsigned char)i;
    if(gamma>0.0 && gamma!=1.0) {
        float exponent=(float)gamma;
        for(i=0;i<256;i++) {
            float base=(float)((double)i*(1.0/255.0));
            int value=(int)(pow((double)base,(double)exponent)*255.0+0.5);
            if(value<0)value=0; if(value>255)value=255;
            megusta_gamma_table[i]=(unsigned char)value;
            if(value!=i)megusta_gamma_active=1;
        }
    }
}
unsigned char megusta_glpng_gammaByte(unsigned char value) {
    return megusta_gamma_active ? megusta_gamma_table[value] : value;
}
"""
needle=b'void APIENTRY pngSetViewingGamma(double viewingGamma) {'
assert original.count(needle)==1
modified = (original.replace(needle,gamma+needle+b'\n\tmegusta_glpng_updateGamma(viewingGamma);') + bridge)
# Apply the model-authored stream adaptation as a retained patch, not a second
# decoder implementation generated by this script. Normalize line endings for
# the patch tool; pinned upstream bytes remain untouched.
extra_patch=root/'patches/glpng/0003-reader-stream.patch'
with tempfile.TemporaryDirectory(prefix='glpng-prepare-',dir=root/'build') as temporary:
    stage=Path(temporary)
    shutil.copytree(source,stage,dirs_exist_ok=True)
    (stage/path).write_bytes(modified.replace(b'\r\n',b'\n'))
    header=stage/'include/GL/glpng.h'
    header.write_bytes(header.read_bytes().replace(b'\r\n',b'\n'))
    subprocess.run(['patch','-p1','-i',str(extra_patch.resolve())],cwd=stage,check=True,capture_output=True)
    modified=(stage/path).read_bytes()
    reader_header=(stage/'include/GL/megusta_reader.h').read_bytes()
    public_header=header.read_bytes()
pins=json.loads((root/'upstream/manifest.json').read_text())['libglpng-1.45']['files']
for name,digest in pins.items():
    assert hashlib.sha256((source/name).read_bytes()).hexdigest()==digest,'Pristine glpng input changed: '+name
if vendor.exists():
    for name in pins:
        expected=modified if name==str(path) else public_header if name=='include/GL/glpng.h' else (source/name).read_bytes()
        assert (vendor/name).read_bytes().replace(b'\r\n',b'\n')==expected.replace(b'\r\n',b'\n'),'Preserve and capture working glpng edits before regenerating: '+name
else:
    shutil.copytree(source, vendor)
reader_path=vendor/'include/GL/megusta_reader.h'
if reader_path.exists():
    assert reader_path.read_bytes().replace(b'\r\n',b'\n')==reader_header,'Preserve reader header edits before regenerating'
(vendor/path).write_bytes(modified)
(vendor/'include/GL/glpng.h').write_bytes(public_header)
(vendor/'include/GL/megusta_reader.h').write_bytes(reader_header)
patch = root/'patches/glpng/0001-mipmap-bridge.patch'
patch.parent.mkdir(parents=True, exist_ok=True)
patch.write_text(''.join(difflib.unified_diff(original.decode().splitlines(True),
    modified.decode().splitlines(True), fromfile='a/src/glpng.c', tofile='b/src/glpng.c')))
(vendor/'megusta-patches.json').write_text(json.dumps({
    'comparison_base': 'glpng 1.45; exact game release not established',
    'upstream_sha256': hashlib.sha256(original).hexdigest(),
    'modified_sha256': hashlib.sha256(modified).hexdigest(),
    'modification': 'MG-GLPNG-001/002/003', 'generator': 'tools/codegen/prepare_glpng.py',
    'reader_patch': str(extra_patch.relative_to(root)),
    'public_header_sha256': hashlib.sha256(public_header).hexdigest(),
    'reader_header_sha256': hashlib.sha256(reader_header).hexdigest(),
}, indent=2)+'\n')
print('Prepared glpng 1.45 with mipmap/gamma changes and unified reader stream')
