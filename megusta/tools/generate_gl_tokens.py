#!/usr/bin/env python3
"""Generate the Win32 token table from the existing recovered snapshot."""
import csv,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
with (root/'manifests/gl_token_mappings.tsv').open() as f: rows=list(csv.DictReader(f,delimiter='\t'))
snapshot=json.loads((root/'manifests/evidence/ssg_v0_tokens.json').read_text())
assert snapshot['table_address']=='00523960' and snapshot['pointer_address']=='00523c04'
values=snapshot['values']
assert len(values)==128 and all(isinstance(v,int) and 0<=v<=0xffffffff for v in values)
indices=set(); lines=['// Generated by tools/generate_gl_tokens.py from the recovered 00523960 table.']
# These multitexture enums are standard OpenGL extension values but are absent
# from the platform's legacy GL 1.1 headers (notably Windows' opengl32 headers).
header_independent_values={'GL_MAX_TEXTURE_UNITS':0x84e2,'GL_TEXTURE0':0x84c0,'GL_TEXTURE1':0x84c1,'GL_TEXTURE2':0x84c2}
for index,value in enumerate(values):
    lines.append(f'values[{index:#04x}] = {value:#x}u;')
for row in rows:
    index=int(row['token'],16); symbol=row['gl_constant']
    assert index not in indices and 0<=index<0xa5 and re.fullmatch(r'GL_[A-Z0-9_]+',symbol)
    assert row['confidence'] in ('strong','inferred') and row['evidence']
    indices.add(index)
    if index < len(values):
        lines.append(f'static_assert({symbol} == {values[index]:#x}u, "GL token {index:#x}");')
    elif symbol in header_independent_values:
        lines.append(f'values[{index:#04x}] = {header_independent_values[symbol]:#x}u; // {symbol}: standard GL enum')
    else:
        lines.append(f'values[{index:#04x}] = {symbol}; // {row["confidence"]}: call-site mapping')
(root/'src/engine/gl_token_values.inc').write_text('\n'.join(lines)+'\n')
